"""Compile annotated transcripts into a promptfoo test file.

    python -m t2r.build                 # deterministic checks only
    python -m t2r.build --judge         # also an LLM-judge assertion where a rubric exists

Writes generated/tests.yaml. The deterministic check itself is attached once,
in promptfooconfig.yaml (defaultTest), so this file only carries data.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

from t2r.transcripts import all_checkpoints

ROOT = Path(__file__).resolve().parent.parent
JUDGE_PROVIDER = "anthropic:messages:claude-opus-5-5"


def build(transcripts_dir: Path, judge: bool = False) -> list[dict]:
    tests = []
    for cp in all_checkpoints(transcripts_dir):
        expect = {k: v for k, v in cp.expect.items() if k != "rubric"}
        test: dict = {
            "description": f"{cp.test_id} · {cp.title}",
            "vars": {
                "test_id": cp.test_id,
                "messages": json.dumps(cp.messages, ensure_ascii=False),
                "expect": json.dumps(expect, ensure_ascii=False),
            },
            "metadata": {"test_id": cp.test_id, "transcript": cp.transcript_id, "tags": cp.tags},
        }
        if judge and cp.expect.get("rubric"):
            test["assert"] = [
                {"type": "llm-rubric", "value": cp.expect["rubric"], "provider": JUDGE_PROVIDER}
            ]
        tests.append(test)
    return tests


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--transcripts", type=Path, default=ROOT / "transcripts")
    parser.add_argument("--out", type=Path, default=ROOT / "generated" / "tests.yaml")
    parser.add_argument("--judge", action="store_true", help="add llm-rubric assertions (needs an API key)")
    args = parser.parse_args()

    tests = build(args.transcripts, judge=args.judge)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by `python -m t2r.build` from transcripts/. Do not edit by hand.\n"
    args.out.write_text(header + yaml.safe_dump(tests, allow_unicode=True, sort_keys=False, width=1000),
                        encoding="utf-8")
    n_transcripts = len({t["metadata"]["transcript"] for t in tests})
    print(f"{len(tests)} checkpoints from {n_transcripts} transcripts -> {args.out}")


if __name__ == "__main__":
    main()
